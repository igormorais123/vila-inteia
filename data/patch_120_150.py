def load_json(filepath):
    """Carrega o JSON do banco de consultores."""
    with open(filepath, 'r', encoding='utf-8') as f:
        return json.load(f)

def generate_patches(data):
    """Gera patches para preenchimento de campos vazios (índices 120-150)."""
    patches = {}

    for idx in range(120, 151):
        if idx >= len(data):
            continue

        consultant = data[idx]
        consultant_data = CONSULTANT_DATA.get(idx)

        if not consultant_data:
            continue

        patch = {}

        # Preencher apenas campos vazios
        for field, value in consultant_data.items():
            if field == "foto_url":  # Skip foto_url conforme instruções
                continue
            if field == "origem_ficcional":  # Skip se não for ficcional
                if not consultant.get("origem_ficcional") and not value:
                    continue

            # Verificar se o campo está vazio no banco
            current_value = consultant.get(field)
            if current_value is None or current_value == "" or (isinstance(current_value, list) and len(current_value) == 0):
                patch[field] = value

        if patch:
            patches[str(idx)] = patch

    return patches

